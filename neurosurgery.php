                            <p>Welcome to the Neurosurgery department at Shri Sai Hospital. Our department is led by Dr. Sanjay Kumar, a highly skilled and experienced neurosurgeon with over 15 years of experience in the field. Dr. Kumar is supported by a team of qualified and experienced neurosurgeons dedicated to providing our patients with the highest care possible.</p>
                            <h3>What is Neurosurgery?</h3>
                            <p>Neurosurgery is a medical specialty that deals with the surgical treatment of conditions affecting the nervous system, including the brain, spinal cord, and nerves. Neurosurgery can treat a wide range of conditions, including brain tumors, spinal cord injuries, and peripheral nervous system disorders.</p>
                            <h3>What Conditions are Treated by our Neurosurgeon at Shri Sai Hospitals?</h3>
                            <p><b>Neurosurgery is used to treat a wide range of neurological conditions, including:</b></p>
                            
                            <ul class="services-features-list mb-10">
                                <li><i class="ri-check-line"></i> <b>Brain Tumors: </b>   Brain tumors are abnormal growths of cells in the brain that can be either cancerous (malignant) or non-cancerous (benign). Neurosurgery may be necessary to remove the tumor or to alleviate pressure on the brain caused by the tumor.</li>
                                <li><i class="ri-check-line"></i> <b>Spinal Cord Injuries: </b>  Spinal cord injuries can be caused by trauma, infection, or degenerative conditions. Neurosurgery may be necessary to repair or stabilize the spine or remove spinal cord tumors.</li>
                                <li><i class="ri-check-line"></i> <b>Epilepsy: </b> Epilepsy is a neurological disorder that causes seizures. Neurosurgery may be necessary to remove the part of the brain responsible for the seizures. </li>
                                <li><i class="ri-check-line"></i> <b>Parkinson's Disease: </b>  Parkinson's disease is a progressive neurological disorder that affects movement. Deep brain stimulation, a neurosurgical procedure that involves implanting a device that sends electrical impulses to the brain, may be used to manage symptoms.</li>
                                <li><i class="ri-check-line"></i> <b>Cerebrovascular Disease:</b>  A cerebrovascular disease is a group of conditions that affect the blood vessels in the brain. Neurosurgery may be necessary to repair or remove damaged blood vessels.</li>
                                <li><i class="ri-check-line"></i> <b>Chiari Malformation: </b>  Chiari malformation is a condition where brain tissue extends into the spinal canal. Neurosurgery may be necessary to alleviate pressure on the brain and spinal cord.</li>
                                <li><i class="ri-check-line"></i> <b>Trigeminal Neuralgia: </b>  Trigeminal neuralgia is a condition that causes severe facial pain. Neurosurgery may be necessary to relieve pressure on the nerve responsible for the pain.</li>
                                <li><i class="ri-check-line"></i> <b>Hydrocephalus: </b>  Hydrocephalus is a condition where there is an excess of cerebrospinal fluid in the brain. Neurosurgery may be necessary to implant a shunt to drain the excess fluid.</li>
                                <li><i class="ri-check-line"></i> <b>Aneurysms: </b> Aneurysms are bulges in the blood vessels in the brain that can rupture and cause bleeding in the brain. Neurosurgery may be necessary to repair or remove the aneurysm. </li>
                                <li><i class="ri-check-line"></i> <b>Movement Disorders: </b> Movement disorders such as dystonia, essential tremor, and Tourette syndrome may be managed with deep brain stimulation surgery.</li>
                            </ul>
                            <h3>What Types of Neurosurgery Procedures are Available?</h3>
                            <p>At Shri Sai Hospital, we offer a comprehensive range of neurosurgery procedures to treat neurological conditions.</p>
                            <p>Some of the most common procedures we perform include:</p>
                             <ul class="services-features-list mb-10">
                                <li><i class="ri-check-line"></i> <b> Brain surgery </b> It includes procedures to remove brain tumors, repair aneurysms, and treat epilepsy. </li>
                                <li><i class="ri-check-line"></i> <b> Spinal surgery </b> It includes procedures to treat spinal cord tumors, repair herniated discs, and relieve spinal stenosis.</li>
                                <li><i class="ri-check-line"></i> <b> Vascular surgery</b> It includes procedures to repair blood vessels in the brain and spinal cord.</li>
                                <li><i class="ri-check-line"></i> <b> Stereotactic radiosurgery </b> This is a non-invasive procedure that uses focused radiation to treat brain tumors and other conditions. </li>
                                <li><i class="ri-check-line"></i> <b>Deep brain stimulation </b>This is a treatment for Parkinson's disease and other movement disorders that involves implanting a device that sends electrical impulses to the brain. </li>
                            </ul>
                            
                            <h3>What diagnostic procedures do we offer at Shri Sai Hospital?</h3>
                            <p>Diagnosis is important in determining whether neurosurgery is necessary to treat a neurological condition. At Shri Sai Hospital, our team of neurosurgeons may use a variety of diagnostic tools and tests to evaluate your condition, including:</p>
                            <ul class="services-features-list mb-10">
                                <li><i class="ri-check-line"></i> <b>Magnetic resonance imaging (MRI) scans: </b> These scans use powerful magnets and radio waves to create detailed brain and nervous system images.</li>
                                <li><i class="ri-check-line"></i> <b>Computed tomography (CT) scans: </b> CT scans use X-rays to create detailed images of the brain and spine.</li>
                                <li><i class="ri-check-line"></i> <b>Electromyography (EMG): </b> This test measures the electrical activity in the muscles and nerves.</li>
                                <li><i class="ri-check-line"></i> <b> Electroencephalogram (EEG): </b> This test measures the electrical activity in the brain.</li>
                                <li><i class="ri-check-line"></i> <b>Positron emission tomography (PET) scans: </b>These scans use a radioactive substance to create brain images and detect abnormalities. </li>
                                <li><i class="ri-check-line"></i> <b>Angiograms: </b> These tests use X-rays and contrast dye to create images of the blood vessels in the brain and detect any abnormalities.</li>
                                <li><i class="ri-check-line"></i> <b>Lumbar puncture:  </b> This test involves inserting a needle into the lower back to collect cerebrospinal fluid for analysis.</li>
                                <li><i class="ri-check-line"></i> <b> Neurological examination: </b> This exam involves testing the patient's reflexes, coordination, and sensation to evaluate neurological function. </li>
                             
                            </ul>
                            <h3>How to Prepare for Neurosurgery?</h3>
                            <p>Preparing for neurosurgery requires careful planning and preparation. Here are some tips to help you prepare for your procedure:</p>
                            <ul>
                                 <li><i class="ri-check-line"></i> Follow your neurosurgeon's instructions regarding diet, medication, and activity restrictions.</li>
                                <li><i class="ri-check-line"></i> Make sure to arrange for someone to take you to and from the hospital on the day of your surgery.</li>
                                <li><i class="ri-check-line"></i> Pack a bag with comfortable clothing, toiletries, and any other items you may need during your hospital stay.</li>
                                 <li><i class="ri-check-line"></i> Discuss any concerns or questions with your neurosurgeon before the procedure.</li>
                            </ul>
